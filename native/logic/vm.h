// Zalard native logic: a tiny virtual machine. The protection-critical guard (does the jar's token
// match, and is a debugger attached?) is not compiled as a plain cmp/jz a cracker can spot and NOP —
// it's hand-assembled into bytecode for this stack VM and run by the interpreter below. To defeat it
// you first have to reverse the VM and the program, not just flip a branch.
//
// This virtualizes the guard, not the whole client: virtualizing everything would be enormous and
// far too slow. A determined reverser can still VM-reverse it; it raises the bar, like the rest.
#pragma once

namespace z {
namespace vm {

// Per-release polymorphic encoding: opcode byte values (VM_OP_*), the XOR-pack key/schedule
// (VM_PROG_KEY / VM_PROG_MUL), and the packed guard program (VM_PROG) are all regenerated by
// tools/gen_guard.py every build, so no two releases share an opcode table or a single program byte.
// The interpreter below is fixed; only what it decodes changes. (Run gen_guard.py before building.)
#include "vm_gen.h"

// The program is stored XOR-packed (so .rdata shows no opcodes) and decoded into a local buffer right
// before it runs. args: [0]=token hi from jar, [1]=token lo, [2]=debugger?1:0, [3]=baked token hi,
// [4]=baked token lo. Logic: r = (a0 ^ a3) | (a1 ^ a4) | a2 ; RET r   (0 <=> token matches, no debugger)
static u64 run(const u64* args, int argc) {
    unsigned char code[sizeof VM_PROG];
    const volatile unsigned char* vp = (const volatile unsigned char*)VM_PROG;  // volatile: don't fold the decode away
    for (unsigned i = 0; i < sizeof VM_PROG; i++)
        code[i] = (unsigned char)(vp[i] ^ VM_PROG_KEY ^ ((i * VM_PROG_MUL) & 0xFF));
    u64 st[16]; int sp = 0;
    // Every op validates stack depth (and the operand byte for PUSH_ARG/PUSH_IMM) BEFORE touching st[],
    // so a tampered / mis-decoded program can't under/overflow the stack to read or write out of bounds,
    // and can't luck into returning 0 ("pass") from garbage: anything malformed returns 1 ("fail").
    for (unsigned ip = 0; ip < sizeof code;) {
        unsigned char op = code[ip++];
        switch (op) {
            case VM_OP_PUSH_ARG: {
                if (ip >= sizeof code || sp >= 16) return 1;  // need the index byte and a free slot
                int k = code[ip++];
                st[sp++] = (k >= 0 && k < argc) ? args[k] : 0;
                break;
            }
            case VM_OP_PUSH_IMM: {                            // used for stack-neutral junk padding
                if (ip >= sizeof code || sp >= 16) return 1;
                st[sp++] = code[ip++];
                break;
            }
            case VM_OP_DROP: { if (sp < 1) return 1; --sp; break; }
            case VM_OP_XOR:  { if (sp < 2) return 1; u64 b = st[--sp], a = st[--sp]; st[sp++] = a ^ b; break; }
            case VM_OP_OR:   { if (sp < 2) return 1; u64 b = st[--sp], a = st[--sp]; st[sp++] = a | b; break; }
            case VM_OP_AND:  { if (sp < 2) return 1; u64 b = st[--sp], a = st[--sp]; st[sp++] = a & b; break; }
            case VM_OP_NOT:  { if (sp < 1) return 1; u64 a = st[--sp]; st[sp++] = a == 0 ? 1 : 0; break; }
            case VM_OP_RET:  if (sp < 1) return 1; return st[--sp];
            default:         return 1;                        // tampered program -> "fail"
        }
    }
    return 1;
}

// The guard: true only if the jar's token matches the baked one and no debugger is present.
static bool guard(u64 jarHi, u64 jarLo) {
    u64 args[5] = { jarHi, jarLo, debuggerPresent() ? 1u : 0u, ZAL_TOKEN_HI, ZAL_TOKEN_LO };
    return run(args, 5) == 0;
}

} // namespace vm
} // namespace z
