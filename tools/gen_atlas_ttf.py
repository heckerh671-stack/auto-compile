# Bakes a real TTF/OTF into the GUI font atlas header (native/font_atlas.h), drop-in for the shader.
#
#   python3 tools/gen_atlas_ttf.py native/font_atlas.h atlas_preview.png
#
# The shader samples the MEDIAN of the atlas RGB channels, so a single-channel SDF replicated into all
# three renders identically to the old MSDF path -- no shader change. SDF (vs MSDF) only rounds sharp
# corners, which is irrelevant for a smooth humanist face like Inter (MSDF only mattered for the old
# hand-drawn pixel font). Metrics follow native/zalard_gui.cpp text(): gx=pen+xoff*sz, gy=base+yoff*sz,
# baseline = cy + CAP_H*size/2, all in em; atlas cell = ink bbox + PAD px margin.
import os, sys
import numpy as np
from PIL import Image, ImageFont, ImageDraw
from scipy.ndimage import distance_transform_edt

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_H   = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "native", "font_atlas.h")
OUT_PNG = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, "..", "atlas_preview.png")

EM, PAD, ATLAS_W, SS = 40, 6, 1024, 8          # em px, margin px, atlas width, supersample
PXRANGE = 2 * PAD
FONTDIR = "/usr/share/fonts/opentype/inter"
FACES = [("FACE_REG", "Inter-Regular.otf"), ("FACE_SEMI", "Inter-SemiBold.otf"),
         ("FACE_MONO", "Inter-Regular.otf"), ("FACE_PIX", "Inter-Medium.otf"),
         ("FACE_PIXB", "Inter-SemiBold.otf")]
EXTRA = [215, 8212, 8230, 183]                 # × — … ·
CHARS = [chr(c) for c in range(32, 127)] + [chr(c) for c in EXTRA]   # 95 + 4 = 99

def sdf_cell(font, ch, ascent):
    adv = font.getlength(ch) / (EM * SS)
    bb = font.getbbox(ch)                      # ink (l,t,r,b), anchor 'la': y=0 ascender, baseline=ascent
    inkW, inkH = bb[2] - bb[0], bb[3] - bb[1]
    if inkW <= 0 or inkH <= 0:
        return dict(w=0, h=0, xoff=0.0, yoff=0.0, adv=adv, cell=None)
    cellW = int(np.ceil(inkW / SS)) + 2 * PAD
    cellH = int(np.ceil(inkH / SS)) + 2 * PAD
    img = Image.new("L", (cellW * SS, cellH * SS), 0)
    ImageDraw.Draw(img).text((PAD * SS - bb[0], PAD * SS - bb[1]), ch, fill=255, font=font)
    a = np.asarray(img, dtype=np.float32)
    mask = a > 127.0
    if not mask.any():
        return dict(w=0, h=0, xoff=0.0, yoff=0.0, adv=adv, cell=None)
    sd = (distance_transform_edt(mask) - distance_transform_edt(~mask)) / SS      # +inside, atlas px
    val = np.clip(0.5 + sd / PXRANGE, 0, 1).reshape(cellH, SS, cellW, SS).mean(axis=(1, 3))
    xoff = bb[0] / (EM * SS) - PAD / EM                       # ink left bearing - margin
    yoff = -(ascent - bb[1]) / (EM * SS) - PAD / EM           # -(ink top above baseline) - margin
    return dict(w=cellW, h=cellH, xoff=xoff, yoff=yoff, adv=adv, cell=val)

faces, cap_h = [], []
for _name, fn in FACES:
    font = ImageFont.truetype(os.path.join(FONTDIR, fn), EM * SS)
    ascent, _desc = font.getmetrics()
    cap_h.append((ascent - font.getbbox("H")[1]) / (EM * SS))
    faces.append([sdf_cell(font, ch, ascent) for ch in CHARS])

# shelf-pack every inked cell into one atlas, tallest first
cells = [(fi, gi, g) for fi, face in enumerate(faces) for gi, g in enumerate(face) if g["cell"] is not None]
cells.sort(key=lambda t: -t[2]["h"])
atlas = np.zeros((1024, ATLAS_W), dtype=np.float32)
x = y = rowh = 0
for _fi, _gi, g in cells:
    if x + g["w"] > ATLAS_W:
        x, y, rowh = 0, y + rowh, 0
    if y + g["h"] > atlas.shape[0]:
        atlas = np.vstack([atlas, np.zeros((g["h"] + 128, ATLAS_W), np.float32)])
    atlas[y:y + g["h"], x:x + g["w"]] = g["cell"]
    g["x"], g["y"] = x, y
    x += g["w"]; rowh = max(rowh, g["h"])
ATLAS_H = y + rowh
atlas = atlas[:ATLAS_H]
for face in faces:
    for g in face:
        g.setdefault("x", 0); g.setdefault("y", 0)

rgb = np.repeat((np.clip(atlas, 0, 1) * 255 + 0.5).astype(np.uint8)[:, :, None], 3, axis=2)
Image.fromarray(rgb).save(OUT_PNG)

def gl(g): return "{%d,%d,%d,%d,%.5ff,%.5ff,%.5ff}" % (g["x"], g["y"], g["w"], g["h"], g["xoff"], g["yoff"], g["adv"])
out = ["// Generated by tools/gen_atlas_ttf.py - do not edit. SDF (RGB-replicated) atlas from Inter.",
       "#pragma once",
       "#define ATLAS_W %d" % ATLAS_W, "#define ATLAS_H %d" % ATLAS_H, "#define ATLAS_CH 3",
       "#define GLYPH_COUNT %d" % len(CHARS), "#define ATLAS_EM %d" % EM]
for i, (name, _fn) in enumerate(FACES):
    out.append("#define %s %d" % (name, i))
out.append("#define PIX_EMF 10.0f")
out.append("static const unsigned int EXTRA_CPS[] = {%s};" % ",".join(str(c) for c in EXTRA))
out.append("static const float CAP_H[] = {%s};" % ",".join("%.5ff" % c for c in cap_h))
out.append("struct GlyphInfo { short x, y, w, h; float xoff, yoff, adv; };")
out.append("static const GlyphInfo GLYPHS[%d][%d] = {" % (len(FACES), len(CHARS)))
for face in faces:
    out.append(" {" + ",".join(gl(g) for g in face) + ",},")
out.append("};")
flat = rgb.reshape(-1)
out.append("static const unsigned char ATLAS_PIXELS[%d] = {" % flat.size)
out.append(",".join(map(str, flat.tolist())))
out.append("};")
open(OUT_H, "w").write("\n".join(out) + "\n")
print("faces=%d glyphs=%d atlas=%dx%d cap_h=%.3f bytes=%d" % (len(FACES), len(CHARS), ATLAS_W, ATLAS_H, cap_h[0], flat.size))
