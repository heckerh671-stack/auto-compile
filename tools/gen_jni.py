# Generates native/logic/jni_table.h: binds the native methods with RegisterNatives from JNI_OnLoad
# instead of exporting 60-odd descriptive Java_dev_zalard_* symbols. The DLL then exports one function
# (JNI_OnLoad); the method-name strings are XS-obfuscated. Run after changing any native method.
import os, re
HERE = os.path.dirname(os.path.abspath(__file__))
NATIVE = os.path.join(HERE, "..", "native")

TMAP = {"void": "V", "jint": "I", "jfloat": "F", "jlong": "J", "jdouble": "D", "jboolean": "Z",
        "jstring": "Ljava/lang/String;", "jdoubleArray": "[D", "jintArray": "[I"}
OBJ_RET = {"vertexBuffer": "Ljava/nio/ByteBuffer;", "atlasPixels": "Ljava/nio/ByteBuffer;"}

def param_type(p):
    p = p.strip()
    if not p: return None
    toks = p.split()
    t = toks[0]
    if t in ("JNIEnv", "JNIEnv*", "jclass", "JavaVM", "JavaVM*"): return None
    if t.endswith("*") and t not in TMAP: return None   # JNIEnv *env style
    return TMAP.get(t, "?" + t)

def parse(path, macro):
    out = []
    s = open(path).read()
    for m in re.finditer(macro + r"\(\s*(\w+)\s*,\s*(\w+)\s*\)\s*\(([^)]*)\)", s):
        ret, name, params = m.group(1), m.group(2), m.group(3)
        sig = "("
        for p in params.split(","):
            t = param_type(p)
            if t: sig += t
        sig += ")"
        if ret == "jobject":
            sig += OBJ_RET.get(name, "Ljava/lang/Object;")
        else:
            sig += TMAP.get(ret, "?" + ret)
        out.append((name, sig))
    return out

mn = parse(os.path.join(NATIVE, "zalard_gui.cpp"), "JFN")
z = parse(os.path.join(NATIVE, "logic", "entry.h"), "ZFN")

# cross-check against the Java native method names
def java_natives(rel):
    s = open(os.path.join(NATIVE, "..", "src", "main", "java", rel)).read()
    return set(re.findall(r"native\s+\w+(?:\[\])?\s+(\w+)\s*\(", s))
jmn = java_natives("dev/zalard/nativegui/ZalardNative.java")
jz = java_natives("dev/zalard/nat/Z.java")
for nm, _ in mn:
    assert nm in jmn, f"JFN {nm} has no Java native in ZalardNative"
for nm, _ in z:
    assert nm in jz, f"ZFN {nm} has no Java native in Z"
missing = (jmn - {n for n, _ in mn}) | (jz - {n for n, _ in z})
assert not missing, f"Java native(s) with no JFN/ZFN: {missing}"

def table(var, cls, rows, prefix):
    o = [f'    jclass {var} = env->FindClass(XS("{cls}"));',
         f'    if ({var}) {{',
         f'        JNINativeMethod _m[] = {{']
    for name, sig in rows:
        o.append(f'            {{ (char*)XS("{name}"), (char*)"{sig}", (void*){prefix}{name} }},')
    o.append('        };')
    o.append(f'        rc{var[1:]} = env->RegisterNatives({var}, _m, (jint)(sizeof(_m) / sizeof(_m[0])));')
    o.append(f'        env->DeleteLocalRef({var});')
    o.append('    }')
    return "\n".join(o)

body = """// Generated by tools/gen_jni.py - do not edit. Binds native methods via RegisterNatives so the DLL
// exports only JNI_OnLoad (not a labelled map of Java_dev_zalard_* functions). Method names are XS'd.
#pragma once

#if defined(MAKO_HARNESS)
#define ZAL_EXPORT extern "C"
#elif defined(_WIN32)
#define ZAL_EXPORT extern "C" __declspec(dllexport)
#else
#define ZAL_EXPORT extern "C" __attribute__((visibility("default")))
#endif

ZAL_EXPORT jint JNICALL JNI_OnLoad(JavaVM* vm, void*) {
    JNIEnv* env = nullptr;
    if (vm->GetEnv((void**)&env, JNI_VERSION_1_6) != JNI_OK || !env) return JNI_ERR;
    jint rc1 = -1, rc2 = -1;   // stays -1 if FindClass returns null; set to RegisterNatives' result below
%s
%s
    if (env->ExceptionCheck()) env->ExceptionClear();
    // A failed class lookup (rc still -1) or a failed RegisterNatives (rc < 0) must abort the load — not
    // limp on with some natives unbound. JNI_ERR makes System.load throw, so ZalardNative disables cleanly.
    if (rc1 != 0 || rc2 != 0) return JNI_ERR;
    return JNI_VERSION_1_6;
}
""" % (table("c1", "dev/zalard/nativegui/ZalardNative", mn, "mn_"),
       table("c2", "dev/zalard/nat/Z", z, "z_"))

open(os.path.join(NATIVE, "logic", "jni_table.h"), "w").write(body)
print(f"registered {len(mn)} ZalardNative + {len(z)} Z methods")
