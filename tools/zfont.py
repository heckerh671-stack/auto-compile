# zfont - Zalard's own pixel font. Original hand-drawn 5x7 bitmaps (cap height 7, x-height 5,
# descenders 2 below the baseline), authored here so the client ships no third-party typeface.
#
# glyph(ch) hands tools/gen_atlas.py each glyph's pixel outline straight to msdfgen:
#   (mask[rows, cols] top->bottom bool, left column index, top = grid row of the top pixel row
#    (grid row 0 is the first row above the baseline), advance in font pixels)
# A glyph is written as (top, [rows]) where row 0 is the topmost pixel row and '#' is ink. Border
# rows/cols that are empty get trimmed (top is adjusted) so the drawings can be padded freely.
