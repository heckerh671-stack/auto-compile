SPACE_ADV = 4

_cache = {}
def glyph(ch):
    """(mask top->bottom, left, top = grid row of the top pixel row, advance in font pixels)."""
    if ch in _cache: return _cache[ch]
    spec = G.get(ch) or G.get("?")
    top, rows = spec
    if not rows:                                   # space / empty
        r = (None, 0, 0, SPACE_ADV); _cache[ch] = r; return r
    w = max(len(s) for s in rows)
    m = np.zeros((len(rows), w), bool)
    for ri, s in enumerate(rows):
        for cj, cch in enumerate(s):
            if cch == "#": m[ri, cj] = True
    if not m.any():
        r = (None, 0, 0, SPACE_ADV); _cache[ch] = r; return r
    rr = np.nonzero(m.any(1))[0]; cc = np.nonzero(m.any(0))[0]
    m2 = m[rr[0]:rr[-1] + 1, cc[0]:cc[-1] + 1]
    top2 = top - int(rr[0])                        # trimming empty top rows lowers the top index
    left = int(cc[0])
    r = (m2, left, top2, m2.shape[1] + 1)
    _cache[ch] = r
    return r

if __name__ == "__main__":
    import sys
    text = "COMBAT  TBot Aim Assist Shield Breaker 0-2  Keybind None  Reset  Configs anarchy {x1.5}"
    W, H = 920, 14
    img = np.zeros((H * 2 + 4, W), bool)
    for line, bold in ((0, False), (1, True)):
        pen = 2; base = 10 + line * (H + 2)
        for ch in text:
            m, l, t, adv = glyph(ch)
            if m is None: pen += adv; continue
            if bold:
                z = np.zeros((m.shape[0], 1), bool)
                m = np.hstack([m, z]) | np.hstack([z, m])
            h, w = m.shape
            y0 = base - t
            img[y0:y0 + h, pen + l:pen + l + w] |= m
            pen += l + w + 1
    from PIL import Image
    Image.fromarray((img * 255).astype(np.uint8)).resize((W * 3, img.shape[0] * 3), Image.NEAREST).save(
        sys.argv[1] if len(sys.argv) > 1 else "/tmp/zfont.png")
    print("wrote preview")
