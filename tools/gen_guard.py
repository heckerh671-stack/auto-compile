# Regenerates the per-release integrity token shared by the DLL and the jar. Run once per release
# (before building the DLL): writes native/logic/guard_token.h and the token constants in
# dev/zalard/nat/Z.java. A built DLL and the source jar then only work together.
import os, sys, secrets, hashlib, random
HERE = os.path.dirname(os.path.abspath(__file__))
hi = secrets.randbits(64)
lo = secrets.randbits(64)
# Per-release payload key. It is NOT written into the jar anywhere — not into ZalardNative.java, not into
# the native stub. It is held by the auth server and handed to the client at launch after a free login, so
# the shipped jar carries only ciphertext. gen_guard writes the key to tools/.release_key (gitignored, used
# by seal.py to encrypt) and prints it so you can set it as the server's PAYLOAD_KEY secret.
_raw_key = secrets.token_bytes(32)
open(os.path.join(HERE, "..", "native", "logic", "guard_token.h"), "w").write(
    "// Generated by tools/gen_guard.py - do not edit. Per-release jar<->DLL binding token.\n"
    "#pragma once\n"
    f"#define ZAL_TOKEN_HI 0x{hi:016X}ULL\n"
    f"#define ZAL_TOKEN_LO 0x{lo:016X}ULL\n")

# ---- polymorphic VM encoding (native/logic/vm_gen.h) --------------------------------------------
# The guard interpreter in vm.h is fixed, but EVERYTHING it decodes is regenerated here each release:
# fresh (distinct) byte values for every opcode, the guard program re-assembled with those opcodes and
# laced with stack-neutral junk, and a fresh XOR-pack key + schedule. Net effect: two releases share no
# opcode values and no program bytes, so a devirtualizer reverse-engineered against one build is dead on
# the next. The VM stays semantically identical (same guard logic); only its encoding is polymorphic.
OPS = ["PUSH_ARG", "PUSH_IMM", "DROP", "XOR", "OR", "AND", "NOT", "RET"]
_op = dict(zip(OPS, random.sample(range(0x01, 0x100), len(OPS))))   # distinct random byte per opcode

# guard program:  r = (a0 ^ a3) | (a1 ^ a4) | a2 ;  RET r      (0  <=>  token matches and no debugger)
_asm = [("PUSH_ARG", 0), ("PUSH_ARG", 3), ("XOR",),
        ("PUSH_ARG", 1), ("PUSH_ARG", 4), ("XOR",), ("OR",),
        ("PUSH_ARG", 2), ("OR",), ("RET",)]
_code = []
for _i, _ins in enumerate(_asm):
    if _i > 0 and random.random() < 0.5:                            # stack-neutral junk between ops
        _code += [_op["PUSH_IMM"], random.randint(0, 255), _op["DROP"]]
    _code.append(_op[_ins[0]])
    if _ins[0] in ("PUSH_ARG", "PUSH_IMM"):
        _code.append(_ins[1] & 0xFF)

_key = random.randint(1, 255)
_mul = random.choice([3, 5, 9, 11, 13, 15])                          # odd pack schedule, != old fixed 7
_packed = [(c ^ _key ^ ((i * _mul) & 0xFF)) & 0xFF for i, c in enumerate(_code)]

_vm = "// Generated by tools/gen_guard.py - do not edit. Per-release polymorphic VM encoding.\n#pragma once\n"
_vm += "".join(f"#define VM_OP_{o} 0x{_op[o]:02X}\n" for o in OPS)
_vm += f"#define VM_PROG_KEY 0x{_key:02X}\n#define VM_PROG_MUL {_mul}\n"
_vm += "static const unsigned char VM_PROG[] = { " + ", ".join(f"0x{b:02X}" for b in _packed) + " };\n"
open(os.path.join(HERE, "..", "native", "logic", "vm_gen.h"), "w").write(_vm)
# patch Z.java token constants
zp = os.path.join(HERE, "..", "src", "main", "java", "dev", "zalard", "nat", "Z.java")
import re
s = open(zp).read()
s = re.sub(r"long TOKEN_HI = 0x[0-9A-Fa-f]+L;", f"long TOKEN_HI = 0x{hi:016X}L;", s)
s = re.sub(r"long TOKEN_LO = 0x[0-9A-Fa-f]+L;", f"long TOKEN_LO = 0x{lo:016X}L;", s)
open(zp, "w").write(s)
# The payload key goes to NO jar source. It is written to tools/.release_key (gitignored) for seal.py to
# encrypt with, and printed so you can set it as the auth server's PAYLOAD_KEY secret. The jar ships only
# ciphertext; the client fetches this key from the server at launch.
# The key must MATCH the server's PAYLOAD_KEY, so it is STABLE across builds: if tools/.release_key already
# holds a valid key it is reused (only the guard token + VM rotate per build). To rotate the key, delete
# tools/.release_key and update the server secret. In CI, write your key secret to tools/.release_key
# before this step so every build encrypts with the key the server serves.
_secret = os.path.join(HERE, ".release_key")
if os.path.exists(_secret):
    try:
        _existing = bytes.fromhex(open(_secret).read().strip())
        if len(_existing) == 32:
            _raw_key = _existing                       # reuse the stable key that matches the server
    except ValueError:
        pass
_keyhex = _raw_key.hex()
open(_secret, "w").write(_keyhex + "\n")
try:
    os.chmod(_secret, 0o600)
except OSError:
    pass
print(f"token {hi:016X}{lo:016X}")
# SECURITY: never print the key in an automated/CI log. Pass --quiet (CI does) to suppress it; interactively
# it's printed once so you can set it as the server's PAYLOAD_KEY secret.
if "--quiet" not in sys.argv:
    print(f"\nPAYLOAD_KEY for the auth server (wrangler secret put PAYLOAD_KEY):\n  {_keyhex}")
    print(f"(also written to {os.path.relpath(_secret)} for tools/seal.py — keep it out of the jar and git)")
else:
    print("payload key written to tools/.release_key (not shown; --quiet)")
